-- LocalDesk demo schema. Run in local Supabase Studio SQL Editor.
create table if not exists public.tasks (
  id bigint generated by default as identity primary key,
  title text not null check (char_length(trim(title)) between 1 and 200),
  category text not null default 'Personal'
    check (category in ('Study', 'Work', 'Personal', 'Life')),
  done boolean not null default false,
  created_at timestamptz not null default now()
);

alter table public.tasks enable row level security;

drop policy if exists "local demo read tasks" on public.tasks;
drop policy if exists "local demo insert tasks" on public.tasks;
drop policy if exists "local demo update tasks" on public.tasks;
drop policy if exists "local demo delete tasks" on public.tasks;

create policy "local demo read tasks" on public.tasks for select to anon using (true);
create policy "local demo insert tasks" on public.tasks for insert to anon with check (true);
create policy "local demo update tasks" on public.tasks for update to anon using (true) with check (true);
create policy "local demo delete tasks" on public.tasks for delete to anon using (true);

grant usage on schema public to anon;
grant select, insert, update, delete on public.tasks to anon;
grant usage, select on sequence public.tasks_id_seq to anon;
