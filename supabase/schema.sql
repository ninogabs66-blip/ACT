-- LocalDesk secure baseline for Supabase.
-- Anonymous clients are denied access. The app must implement Supabase Auth
-- and send a signed-in user's session before remote CRUD can work.

create table if not exists public.tasks (
  id bigint generated by default as identity primary key,
  user_id uuid not null default auth.uid() references auth.users(id) on delete cascade,
  title text not null check (char_length(trim(title)) between 1 and 200),
  category text not null default 'Personal'
    check (category in ('Study', 'Work', 'Personal', 'Life')),
  done boolean not null default false,
  created_at timestamptz not null default now()
);

-- Safe migration for a table created by an earlier demo schema.
alter table public.tasks add column if not exists user_id uuid references auth.users(id) on delete cascade;

-- Old anonymous-demo rows have no owner. Do not assign them to a user automatically.
-- They remain inaccessible under these policies until an administrator reviews them.
alter table public.tasks enable row level security;
alter table public.tasks force row level security;

drop policy if exists "local demo read tasks" on public.tasks;
drop policy if exists "local demo insert tasks" on public.tasks;
drop policy if exists "local demo update tasks" on public.tasks;
drop policy if exists "local demo delete tasks" on public.tasks;
drop policy if exists "users read own tasks" on public.tasks;
drop policy if exists "users insert own tasks" on public.tasks;
drop policy if exists "users update own tasks" on public.tasks;
drop policy if exists "users delete own tasks" on public.tasks;

create policy "users read own tasks"
  on public.tasks for select to authenticated
  using ((select auth.uid()) = user_id);

create policy "users insert own tasks"
  on public.tasks for insert to authenticated
  with check ((select auth.uid()) = user_id);

create policy "users update own tasks"
  on public.tasks for update to authenticated
  using ((select auth.uid()) = user_id)
  with check ((select auth.uid()) = user_id);

create policy "users delete own tasks"
  on public.tasks for delete to authenticated
  using ((select auth.uid()) = user_id);

-- Explicitly remove anonymous and PUBLIC table/sequence access.
revoke all on public.tasks from anon, public;
revoke all on sequence public.tasks_id_seq from anon, public;
grant select, insert, update, delete on public.tasks to authenticated;
grant usage, select on sequence public.tasks_id_seq to authenticated;

create index if not exists tasks_user_completed_created_at_idx
  on public.tasks (user_id, created_at)
  where done = true;

-- Cleanup only the signed-in caller's completed tasks older than 30 days.
create or replace function public.cleanup_old_completed_tasks()
returns integer
language plpgsql
security invoker
set search_path = ''
as $$
declare
  removed_count integer;
begin
  if auth.uid() is null then
    raise exception 'Authentication required';
  end if;

  delete from public.tasks
  where user_id = auth.uid()
    and done = true
    and created_at < now() - interval '30 days';

  get diagnostics removed_count = row_count;
  return removed_count;
end;
$$;

revoke all on function public.cleanup_old_completed_tasks() from public, anon;
grant execute on function public.cleanup_old_completed_tasks() to authenticated;
